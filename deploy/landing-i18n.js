  function applyRules(text, language) {
    if (language === "fr") return null;
    for (var index = 0; index < RULES.length; index += 1) {
      var rule = RULES[index];
      var match = rule.pattern.exec(text);
      if (match) {
        var template = rule.replace[language];
        if (template) {
          return template.replace(/\$(\d)/g, function (_, group) { return match[Number(group)]; });
        }
      }
    }
    return null;
  }

  function decode(value) {
    return value
      .replace(/&lt;/g, "<")
      .replace(/&gt;/g, ">")
      .replace(/&quot;/g, '"')
      .replace(/&#39;/g, "'")
      .replace(/&amp;/g, "&");
  }

  function normalize(value) {
    return decode(value).replace(/[\s\u00a0\u202f]+/g, " ").trim();
  }

